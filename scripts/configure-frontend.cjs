const fs = require('node:fs');
const path = require('node:path');
// This is a public OAuth identifier, never a client secret.
const clientId = (process.env.GOOGLE_CLIENT_ID || '').trim();
if (
  clientId &&
  (!/^\d+-[a-zA-Z0-9_-]+\.apps\.googleusercontent\.com$/.test(clientId) ||
    clientId.includes('-mock.'))
) {
  throw new Error('GOOGLE_CLIENT_ID must be a real Google web client ID.');
}
fs.writeFileSync(
  path.join(__dirname, '../apps/mehrchain-frontend/src/environments/google-client-id.generated.ts'),
  `// Generated by scripts/configure-frontend.cjs. Public configuration only.\nexport const googleClientId = ${JSON.stringify(clientId)};\n`,
);
console.log(
  clientId
    ? 'Google sign-in configuration generated.'
    : 'Google sign-in disabled: GOOGLE_CLIENT_ID is not configured.',
);
